// Function to render posts list
function renderPostsList() {
  const postsList = document.getElementById("postsList");
  if (!postsList) return;

  postsList.innerHTML = blogPosts
    .map(
      (post) => `
        <div class="post-item" data-id="${post.id}">
            <h3>${post.title}</h3>
            <div class="post-meta">
                <span>${post.date}</span>
                <span>${post.author}</span>
            </div>
        </div>
    `
    )
    .join("");

  // Add click event listeners
  document.querySelectorAll(".post-item").forEach((item) => {
    item.addEventListener("click", () => {
      item.scrollIntoView({
        behavior: "smooth",
        block: "start",
        inline: "nearest",
      });
      const postId = parseInt(item.dataset.id);
      renderPostDetails(postId);
      document
        .querySelectorAll(".post-item")
        .forEach((p) => p.classList.remove("active"));
      item.classList.add("active");
    });
  });
}

// Function to render post details
function renderPostDetails(postId) {
  const post = blogPosts.find((p) => p.id === postId);
  if (!post) return;

  const postDetails = document.getElementById("postDetails");
  postDetails.innerHTML = `
        <img src="${post.image}" alt="${post.title}">
        <h1>${post.title}</h1>
        <div class="post-meta">
            <span><i class="fas fa-calendar"></i> ${post.date}</span>
            <span><i class="fas fa-user"></i> ${post.author}</span>
        </div>
        <div class="post-tags">
            ${post.tags
              .map((tag) => `<span class="tag">${tag}</span>`)
              .join("")}
        </div>
        <div class="post-content">
            ${post.content}
        </div>
    `;

  // Add smooth scroll to top when changing posts
  postDetails.scrollTo({ top: 0, behavior: "smooth" });

  // Update active state in posts list
  document.querySelectorAll(".post-item").forEach((item) => {
    item.classList.toggle("active", parseInt(item.dataset.id) === postId);
  });
}

// Toggle sidebar with animation
document.getElementById("toggle").addEventListener("click", () => {
  const sidebar = document.querySelector(".sidebar");
  sidebar.classList.toggle("collapse");
});

function initializeSearch() {
  // Search functionality with debounce
  let searchTimeout;
  document.getElementById("search").addEventListener("input", (e) => {
    clearTimeout(searchTimeout);
    searchTimeout = setTimeout(() => {
      const searchTerm = e.target.value.toLowerCase();
      const filteredPosts = blogPosts.filter(
        (post) =>
          post.title.toLowerCase().includes(searchTerm) ||
          post.content.toLowerCase().includes(searchTerm) ||
          post.tags.some((tag) => tag.toLowerCase().includes(searchTerm))
      );

      const postsList = document.getElementById("postsList");
      if (filteredPosts.length === 0) {
        postsList.innerHTML =
          '<div class="no-results">No posts found matching your search.</div>';
      } else {
        postsList.innerHTML = filteredPosts
          .map(
            (post) => `
                <div class="post-item" data-id="${post.id}">
                    <h3>${post.title}</h3>
                    <p class="post-meta">${post.date} • ${post.author}</p>
                </div>
            `
          )
          .join("");

        // Reattach click event listeners
        document.querySelectorAll(".post-item").forEach((item) => {
          item.addEventListener("click", () => {
            const postId = parseInt(item.dataset.id);
            renderPostDetails(postId);
            document
              .querySelectorAll(".post-item")
              .forEach((p) => p.classList.remove("active"));
            item.classList.add("active");
          });
        });
      }
    }, 300); // 300ms debounce
  });
}

// Initialize when DOM is loaded
document.addEventListener("DOMContentLoaded", () => {
  initializeSearch();
  renderPostsList();
  renderPostDetails(1); // Show first post by default
});
