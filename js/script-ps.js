// Function to render posts list
function renderPostsList() {
  const postsList = document.getElementById("postsList");
  postsList.innerHTML = blogPosts
    .map(
      (post) => `
        <div class="post-item" data-id="${post.id}">
            <h3>${post.title}</h3>
            <p class="post-meta">${post.date} • ${post.author}</p>
        </div>
    `
    )
    .join("");

  // Add click event listeners
  document.querySelectorAll(".post-item").forEach((item) => {
    item.addEventListener("click", () => {
      item.scrollIntoView({
        behavior: "smooth",
        block: "start",
        inline: "nearest",
      });

      const postId = parseInt(item.dataset.id);
      renderPostDetails(postId);
      document
        .querySelectorAll(".post-item")
        .forEach((p) => p.classList.remove("active"));
      item.classList.add("active");
    });
  });
}

// Function to render post details
function renderPostDetails(postId) {
  const post = blogPosts.find((p) => p.id === postId);
  const postDetails = document.getElementById("postDetails");
  postDetails.innerHTML = `
        <img src="${post.image}" alt="${post.title}">
        <h1>${post.title}</h1>
        <div class="post-meta">
            <span><i class="fas fa-calendar"></i> ${post.date}</span>
            <span><i class="fas fa-user"></i> ${post.author}</span>
        </div>
        <div class="post-tags">
            ${post.tags
              .map((tag) => `<span class="tag">${tag}</span>`)
              .join("")}
        </div>
        <div class="post-content">
            ${post.content}
        </div>
    `;

  // Add smooth scroll to top when changing posts
  postDetails.scrollTo({ top: 0, behavior: "smooth" });
}

